--------------------------------------------------------------------------------
-- HUERTOHOGAR API - 01 Tablas
-- Base de datos: Oracle XE 21c (columnas IDENTITY)
-- Usuario Oracle: HUERTO_API
--
-- Modelo propuesto por el profesor (Evaluacion 3):
--   USUARIO -> BOLETA -> DETALLE_BOLETA <- PRODUCTO <- CATEGORIA
--
-- Adaptado desde el taller de base de datos (copia en database/taller-copia):
--   clientes      -> USUARIO        (se agrega rol, RUN, region, comuna...)
--   pedidos       -> BOLETA
--   pedido_items  -> DETALLE_BOLETA
--   productos     -> PRODUCTO
--   categorias    -> CATEGORIA
-- No se usan SUCURSALES ni AUDITORIA_ENVIOS: no estan en el modelo del profesor
-- y el frontend no los usa.
--------------------------------------------------------------------------------

--------------------------------------------------------------------------------
-- CATEGORIA
--------------------------------------------------------------------------------
CREATE TABLE categoria (
    categoria_id  NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    nombre        VARCHAR2(100)  NOT NULL,
    descripcion   VARCHAR2(500),
    CONSTRAINT pk_categoria PRIMARY KEY (categoria_id),
    CONSTRAINT uk_categoria_nombre UNIQUE (nombre)
);

--------------------------------------------------------------------------------
-- PRODUCTO
-- descuento_oferta: porcentaje de descuento (0 = sin oferta)
--------------------------------------------------------------------------------
CREATE TABLE producto (
    producto_id       NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    codigo            VARCHAR2(10)   NOT NULL,
    nombre            VARCHAR2(100)  NOT NULL,
    categoria_id      NUMBER         NOT NULL,
    precio            NUMBER(10,2)   NOT NULL,
    stock             NUMBER(10)     DEFAULT 0 NOT NULL,
    unidad_medida     VARCHAR2(20),
    origen            VARCHAR2(100),
    descripcion       VARCHAR2(1000),
    imagen            VARCHAR2(200),
    descuento_oferta  NUMBER(3)      DEFAULT 0 NOT NULL,
    activo            CHAR(1)        DEFAULT 'S' NOT NULL,
    CONSTRAINT pk_producto PRIMARY KEY (producto_id),
    CONSTRAINT uk_producto_codigo UNIQUE (codigo),
    CONSTRAINT fk_producto_categoria FOREIGN KEY (categoria_id)
        REFERENCES categoria (categoria_id),
    CONSTRAINT ck_producto_precio    CHECK (precio >= 0),
    CONSTRAINT ck_producto_stock     CHECK (stock >= 0),
    CONSTRAINT ck_producto_descuento CHECK (descuento_oferta BETWEEN 0 AND 100),
    CONSTRAINT ck_producto_activo    CHECK (activo IN ('S','N'))
);

--------------------------------------------------------------------------------
-- USUARIO
-- rol: Cliente | Vendedor | Administrador (mismos textos que usa el frontend)
-- contrasena: se guarda con hash BCrypt (por eso 100 caracteres)
--------------------------------------------------------------------------------
CREATE TABLE usuario (
    usuario_id        NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    run               VARCHAR2(9)    NOT NULL,
    nombre            VARCHAR2(50)   NOT NULL,
    apellidos         VARCHAR2(100)  NOT NULL,
    correo            VARCHAR2(100)  NOT NULL,
    contrasena        VARCHAR2(100)  NOT NULL,
    fecha_nacimiento  DATE,
    region            VARCHAR2(80),
    comuna            VARCHAR2(80),
    direccion         VARCHAR2(300),
    rol               VARCHAR2(20)   DEFAULT 'Cliente' NOT NULL,
    activo            CHAR(1)        DEFAULT 'S' NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (usuario_id),
    CONSTRAINT uk_usuario_run    UNIQUE (run),
    CONSTRAINT uk_usuario_correo UNIQUE (correo),
    CONSTRAINT ck_usuario_rol    CHECK (rol IN ('Cliente','Vendedor','Administrador')),
    CONSTRAINT ck_usuario_activo CHECK (activo IN ('S','N'))
);

--------------------------------------------------------------------------------
-- BOLETA (la orden de compra)
-- usuario_id puede ser NULL: el frontend permite comprar sin haber iniciado sesion.
-- estado: PAGADA | FALLIDA (el pago es simulado)
--------------------------------------------------------------------------------
CREATE TABLE boleta (
    boleta_id          NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    codigo             VARCHAR2(20)   NOT NULL,
    usuario_id         NUMBER,
    fecha_boleta       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    estado             VARCHAR2(20)   NOT NULL,
    nombre_cliente     VARCHAR2(50)   NOT NULL,
    apellidos_cliente  VARCHAR2(100)  NOT NULL,
    correo_cliente     VARCHAR2(100)  NOT NULL,
    calle              VARCHAR2(300)  NOT NULL,
    departamento       VARCHAR2(50),
    region             VARCHAR2(80)   NOT NULL,
    comuna             VARCHAR2(80)   NOT NULL,
    indicaciones       VARCHAR2(500),
    tipo_entrega       VARCHAR2(20)   NOT NULL,
    metodo_pago        VARCHAR2(30)   NOT NULL,
    subtotal           NUMBER(12,2)   NOT NULL,
    costo_envio        NUMBER(12,2)   DEFAULT 0 NOT NULL,
    total              NUMBER(12,2)   NOT NULL,
    CONSTRAINT pk_boleta PRIMARY KEY (boleta_id),
    CONSTRAINT uk_boleta_codigo UNIQUE (codigo),
    CONSTRAINT fk_boleta_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuario (usuario_id),
    CONSTRAINT ck_boleta_estado  CHECK (estado IN ('PAGADA','FALLIDA')),
    CONSTRAINT ck_boleta_entrega CHECK (tipo_entrega IN ('retiro','domicilio')),
    CONSTRAINT ck_boleta_montos  CHECK (subtotal >= 0 AND costo_envio >= 0 AND total >= 0)
);

--------------------------------------------------------------------------------
-- DETALLE_BOLETA (una fila por producto comprado)
-- precio_unitario guarda el precio que se pagó (ya con oferta), por si luego cambia.
--------------------------------------------------------------------------------
CREATE TABLE detalle_boleta (
    detalle_id       NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
    boleta_id        NUMBER         NOT NULL,
    producto_id      NUMBER         NOT NULL,
    cantidad         NUMBER(10)     NOT NULL,
    precio_unitario  NUMBER(10,2)   NOT NULL,
    subtotal         NUMBER(12,2)   NOT NULL,
    CONSTRAINT pk_detalle_boleta PRIMARY KEY (detalle_id),
    CONSTRAINT fk_detalle_boleta FOREIGN KEY (boleta_id)
        REFERENCES boleta (boleta_id) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_producto FOREIGN KEY (producto_id)
        REFERENCES producto (producto_id),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0)
);

--------------------------------------------------------------------------------
-- INDICES DE APOYO (busquedas por clave foranea)
--------------------------------------------------------------------------------
CREATE INDEX ix_producto_categoria ON producto (categoria_id);
CREATE INDEX ix_boleta_usuario     ON boleta (usuario_id);
CREATE INDEX ix_detalle_boleta     ON detalle_boleta (boleta_id);
CREATE INDEX ix_detalle_producto   ON detalle_boleta (producto_id);
